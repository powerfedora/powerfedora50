// 新闻利好/利空/中性判断：按标题里的措辞打分（规则法，不联网）。
// 只能看标题，看不到正文；判断的是"这条消息对股价的影响方向"，不是对公司好坏的评价。
// 每条规则 [正则, 权重, 理由]；利好、利空各自累加（上限 5），差值 ≥ 1.5 才算利好/利空，否则中性。
const BULL = [
  [/利好/, 3, '标题称利好'],
  [/同比(增长|增加|增|上升|上涨|大增|提升|增超|增近|扭亏)/, 2, '同比增长'],
  [/(净利|利润|营收|收入|盈利|销量|订单|业绩)[^，。；：]{0,6}(增长|大增|增超|增近|增逾|增\d|攀升|提升|翻倍|创新高|创次新高|加速|改善|扭亏|上升)/, 2, '业绩增长'],
  [/双增|增收增利|增速(逐季)?(抬升|提升|加快)|盈利质量改善|扭亏为盈/, 2, '营收利润双增'],
  [/超预期|大超|好于预期|预增|预盈/, 3, '业绩超预期/预增'],
  [/(创|刷新)[^，。；]{0,6}新高/, 2, '创新高'],
  [/涨停|大涨|飙升|暴涨|狂飙|逆势(活跃|增长|上涨)/, 2, '股价强势'],
  [/增持/, 2, '增持'],
  [/拟[^，。；]{0,15}回购|首次回购|已回购/, 2, '回购股份'],
  [/回购注销|注销[^，。；]{0,8}股|提振信心/, 1, '回购注销/提振信心'],
  [/10派\d|每10股派|派息|分红/, 2, '分红派息'],
  [/中标|战略合作|签署[^，。；]{0,8}合作|获批|获受理|优先审评|批量交付|订单饱满|提价|量价齐升|产能释放|开始出货|放量|市占率提升/, 2, '订单/合作/获批等'],
  [/景气度[^，。；]{0,6}(延续|向上|较好|提升)|(延续|保持)较好的景气度|需求[^，。；]{0,4}(爆发|旺盛|强劲)|(提高|上调|调高)[^，。；]{0,6}(预期|目标价|盈利预测)|买入评级|增持评级|获公募/, 2, '景气度/上调预期'],
  [/稳健|韧性|向好|复苏|提速|微增/, 1, '经营稳健/向好']
];
const BEAR = [
  [/利空/, 3, '标题称利空'],
  [/同比(下降|下滑|减少|下跌|降|减|回落|缩水|大降|下挫|转亏)/, 2.5, '同比下降'],
  [/(净利|利润|营收|收入|盈利|销量|销售额|业绩)[^，。；：]{0,6}(下降|下滑|减少|下跌|降\d|降逾|降超|减超|回落|缩水|腰斩|转亏|萎缩|下挫)/, 2.5, '业绩下滑'],
  [/增收不增(利|润)|(利润|净利|营收|盈利)(端)?承压|收入增长承压/, 2.5, '增收不增利/承压'],
  [/承压/, 2, '承压'],
  [/少赚|多花|成本(上升|增加|上涨)|(费用|成本)[^，。；]{0,6}(增长|增加|上升)|原材料(涨价|上涨)/, 2.5, '成本/费用上升'],
  [/预亏|预减|首亏|(?<!扭)亏损|转亏|由盈转亏|巨亏/, 3, '亏损'],
  [/立案|处罚|违规|造假|强制退市|退市|爆雷|违约|被罚|诉讼|仲裁|监管函|警示函|风险警示|风险提示/, 3, '监管/诉讼/退市风险'],
  [/减持|清仓|套现|质押|冻结|问询|暂停|终止|撤回|召回|事故|商誉减值|计提[^，。；]{0,4}减值|资产减值/, 2, '减持/问询/减值等'],
  [/不及[^，。；]{0,6}预期|低于预期|(下调|调低|降低)[^，。；]{0,6}(预期|目标价|评级|盈利预测)|卖出评级|减持评级/, 2.5, '低于预期/下调'],
  [/跌停|大跌|暴跌|重挫|闪崩|低开|跳水|蒸发|估值回调|走弱|杀跌|破位/, 4, '股价大幅回落'],
  [/下滑|下降/, 1.5, '下滑'],
  [/降温|放缓|疲软|萎缩/, 1.5, '增速放缓']
];

function side(title, rules) {
  let sum = 0; const why = [];
  for (const [re, w, tag] of rules) if (re.test(title)) { sum += w; why.push(tag); }
  return { sum: Math.min(sum, 5), why };
}

function classify(title) {
  const t = String(title || '');
  const b = side(t, BULL), r = side(t, BEAR), net = b.sum - r.sum;
  if (net >= 1.5) return { label: 'bull', score: net, why: b.why };
  if (net <= -1.5) return { label: 'bear', score: net, why: r.why };
  const mixed = b.sum >= 2 && r.sum >= 2;
  return { label: 'neutral', score: net, why: mixed ? ['多空交织：' + b.why[0] + ' / ' + r.why[0]] : [] };
}

// 给 [{title,...}] 加上 sentiment 字段（label、理由），不改原对象
const annotate = (arr) => (arr || []).map((n) => { const c = classify(n.title); return { ...n, sentiment: { label: c.label, why: c.why.join('、') } }; });

module.exports = { classify, annotate };
